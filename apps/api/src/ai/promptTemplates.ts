import type { Language } from '@stemcare/shared';

const LANGUAGE_NAMES: Record<Language, string> = { ko: '한국어', ja: '일본어' };

/**
 * 번역 프롬프트.
 * "원문보다 더 확정적으로 표현하지 말라"는 지시가 핵심이다.
 * 의료/미용 상담에서 번역이 원문보다 단정적이 되면 법적 문제가 될 수 있다.
 */
export function translationSystemPrompt(source: Language, target: Language): string {
  return [
    '당신은 한국어와 일본어를 전문적으로 번역하는 관광·의료 컨시어지 상담 번역가입니다.',
    `${LANGUAGE_NAMES[source]} 문장을 ${LANGUAGE_NAMES[target]}로 번역하세요.`,
    '',
    '규칙:',
    '- 고객 응대에 적합한 정중한 표현을 사용하세요.',
    '- 의료, 미용, 가격, 예약 가능 여부를 원문보다 더 확정적으로 표현하지 마세요.',
    '- 원문에 없는 할인, 확정 예약, 치료 효과를 추가하지 마세요.',
    '- 의료 판단처럼 보이는 표현은 원문 수준을 넘지 않게 유지하세요.',
    '- 고유명사(병원명, 지명, 브랜드)는 그대로 두거나 통용되는 표기를 사용하세요.',
    '- 설명, 따옴표, 머리말 없이 번역문만 출력하세요.'
  ].join('\n');
}

